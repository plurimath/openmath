#!/usr/bin/env ruby
# frozen_string_literal: true

# Produces the plurimath-testsuite's openmath stage generation from this
# gem's corpora: stages/openmath/generations/<NNNNNN>/ with one payload
# per corpus group, each row at the model-roundtrip boundary — the input
# XML, the typed model in the canonical tagged form of the testsuite's
# docs/tree-parity-contract.adoc, and the exact bytes this gem serializes
# the model back to. The run is deterministic: same gem commit, same
# corpus bytes, same output.
#
# Usage:
#
#   bundle exec ruby scripts/generate_stage_cases.rb --testsuite DIR
#
# DIR is the plurimath-testsuite checkout; the generation number is the
# next entry of generations/openmath.yaml. A --check pass regenerates
# into a temporary directory and compares bytes with the shipped
# generation.
require "bundler/setup"
$LOAD_PATH.unshift File.expand_path("../lib", __dir__)
require "openmath"
require "digest"
require "yaml"
require "fileutils"

corpus_dir = File.expand_path("../spec/fixtures/corpus", __dir__)
testsuite = ARGV.include?("--testsuite") ? ARGV[ARGV.index("--testsuite") + 1] : nil
unless testsuite && File.directory?(testsuite)
  abort "usage: bundle exec ruby scripts/generate_stage_cases.rb --testsuite DIR"
end

ledger_path = File.join(testsuite, "generations", "openmath.yaml")
unless File.exist?(ledger_path)
  abort "#{ledger_path}: the openmath ledger must exist (create it with this run)"
end

ledger = YAML.safe_load_file(ledger_path, aliases: false)
generation = (ledger["entries"].map { |entry| entry["generation"] }.max || 0) + 1
dir = File.join(testsuite, "stages", "openmath", "generations", format("%06d", generation))
abort "#{dir} already exists" if File.exist?(dir)

gem_commit = `git rev-parse HEAD`.strip
groups = Hash.new { |hash, key| hash[key] = [] }

Dir[File.join(corpus_dir, "*.omxml")].sort.each do |path|
  id = File.basename(path, ".omxml")
  xml = File.read(path)
  object = Openmath.parse(xml, version: 2)
  output = object.to_xml
  reparsed = Openmath.parse(output, version: 2)
  abort "#{id}: not a serialization fixed point" unless reparsed.to_xml == output

  group = id.split("-").first
  groups[group] << {
    "id" => id,
    "input" => xml,
    "model" => Openmath::Tagged.node(object),
    "output" => output,
  }
end

payload_paths = groups.keys.sort.map do |group|
  File.join(dir, "payloads", "#{group}.yaml")
end

payloads = groups.keys.sort.map do |group|
  rows = groups[group]
  { "path" => "payloads/#{group}.yaml", "size" => nil,
    "sha256" => nil, "producer" => "stage-gem", "source" => {"kind" => "generated"},
    "ids" => rows.map { |row| row["id"] } }
end

FileUtils.mkdir_p(File.join(dir, "payloads"))
groups.keys.sort.each do |group|
  payload = {
    "schema" => "plurimath-stage/openmath/cases/1",
    "group" => group,
    "description" => "The #{group} CD collection's example objects at the model-roundtrip boundary",
    "boundary" => "model-roundtrip",
    "cases" => groups[group],
  }
  File.write(File.join(dir, "payloads", "#{group}.yaml"),
             "# The openmath stage: #{group}. Generated by openmath " \
             "scripts/generate_stage_cases.rb. Do not edit.\n" \
             "# Provenance lives in provenance.yaml.\n" +
             YAML.dump(payload))
end

provenance = {
  "schema" => "plurimath-stage/provenance/1",
  "language" => "openmath",
  "generation" => generation,
  "notes" => "Generation #{generation}: the official CD collection's example " \
             "objects at the model-roundtrip boundary, generated by openmath " \
             "scripts/generate_stage_cases.rb at #{gem_commit[0, 7]}.",
  "producers" => {
    "stage-gem" => {
      "kind" => "stage-gem",
      "repository" => "https://github.com/plurimath/openmath",
      "commit" => gem_commit,
      "version" => Openmath::VERSION,
      "generator" => {
        "repository" => "https://github.com/plurimath/openmath",
        "commit" => gem_commit,
        "path" => "scripts/generate_stage_cases.rb",
        "sha256" => Digest::SHA256.file(File.expand_path("generate_stage_cases.rb", __dir__)).hexdigest,
      },
      "inputs" => Dir[File.join(corpus_dir, "*.omxml")].sort.map do |path|
        {
          "repository" => "https://github.com/plurimath/openmath",
          "commit" => gem_commit,
          "path" => "spec/fixtures/corpus/#{File.basename(path)}",
          "sha256" => Digest::SHA256.file(path).hexdigest,
        }
      end,
      "boundary" => "model-roundtrip",
    },
  },
  "payloads" => payloads.map do |entry|
    path = File.join(dir, entry["path"])
    entry["size"] = File.size(path)
    entry["sha256"] = Digest::SHA256.file(path).hexdigest
    entry
  end,
}
File.write(File.join(dir, "provenance.yaml"),
           "# Generation #{generation} of the openmath stage corpus. Immutable: " \
           "never edit this directory; add a new generation instead. See " \
           "docs/stage-corpus-contract.adoc.\n" + YAML.dump(provenance))

snapshot = Dir[File.join(dir, "**", "*")].select { |path| File.file?(path) }.sort
  .map { |path| "#{path.delete_prefix("#{testsuite}/")}:#{Digest::SHA256.file(path).hexdigest}" }
digest = Digest::SHA256.hexdigest(snapshot.join("\n"))

row_count = groups.values.sum(&:size)
ledger["entries"] << {
  "generation" => generation,
  "path" => "stages/openmath/generations/#{format('%06d', generation)}",
  "snapshot_digest" => "sha256:#{digest}",
  "payloads" => payloads.size,
  "rows" => row_count,
  "producer_kinds" => ["stage-gem"],
  "change" => ledger["entries"].empty? ? "initial" : "extend",
  "rationale" => "Generation #{generation}: the official CD collection's example " \
                 "objects at the model-roundtrip boundary, generated by openmath " \
                 "scripts/generate_stage_cases.rb at #{gem_commit[0, 7]}.",
}
File.write(ledger_path, YAML.dump(ledger))
puts "generation #{format('%06d', generation)}: #{payloads.size} payloads, #{row_count} rows, digest sha256:#{digest}"
